#!/usr/bin/env python3
"""Generate the famous-reviews gallery: PIP reviews landmark open-source
projects so visitors can see real report cards before running their own.

Usage: python3 tools/make_gallery.py
Clones each project into a temp dir, reviews it, and writes gallery/ files.
"""
import os
import shutil
import subprocess
import sys
import tempfile
from datetime import date

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import pip_pip  # noqa: E402

PROJECTS = [
    ("requests", "https://github.com/psf/requests"),
    ("flask", "https://github.com/pallets/flask"),
    ("express", "https://github.com/expressjs/express"),
    ("normalize-css", "https://github.com/necolas/normalize.css"),
    ("fastapi", "https://github.com/fastapi/fastapi"),
    ("vue", "https://github.com/vuejs/vue"),
    ("prettier", "https://github.com/prettier/prettier"),
    ("tokio", "https://github.com/tokio-rs/tokio"),
]

ROOT = os.path.join(os.path.dirname(__file__), "..", "gallery")


def main() -> int:
    os.makedirs(ROOT, exist_ok=True)
    index = ["# The PIP Gallery: famous projects, formally reviewed", "",
             "Every card below was generated by PIP itself from the project's real git",
             "history. No author was consulted. Several would like to speak to HR.", ""]
    for slug, url in PROJECTS:
        print(f"== {slug} ({url})")
        tmp_root = tempfile.mkdtemp(prefix=f"gallery-{slug}-")
        tmp = os.path.join(tmp_root, slug)  # basename becomes the repo name on cards
        try:
            subprocess.run(["git", "clone", "--quiet", url, tmp],
                           check=True, timeout=900)
            commits = pip_pip.collect_commits(tmp, 5000)
            stats, file_totals, paths_by_sha = pip_pip.collect_numstat(tmp, {c.sha for c in commits})
            for c in commits:
                if c.sha in stats:
                    c.added, c.deleted, c.files = stats[c.sha]
                c.paths = tuple(paths_by_sha.get(c.sha, ()))
            markers = pip_pip.collect_markers(tmp)
            board = pip_pip.leaderboard(tmp, commits, markers, date.today(),
                                         file_totals=file_totals, top=5)
            if not board:
                print(f"   skipped: no reviews produced")
                continue
            top = board[0]
            outdir = os.path.join(ROOT, slug)
            os.makedirs(outdir, exist_ok=True)
            with open(os.path.join(outdir, "card.svg"), "w", encoding="utf-8") as f:
                f.write(pip_pip.render_svg(top))
            with open(os.path.join(outdir, "review.md"), "w", encoding="utf-8") as f:
                f.write(pip_pip.render_markdown(top))
            index.append(f"## {top.repo_name}")
            index.append("")
            index.append(f"Top author: **{top.author}**, grade **{top.overall_letter} "
                         f"({top.overall_score:.0f}/100)**, {top.total_commits} commits reviewed.")
            index.append("")
            index.append(f"![{top.author} report card]({slug}/card.svg)")
            index.append("")
            index.append("| # | Author | Grade | Score | Commits |")
            index.append("| --- | --- | --- | --- | --- |")
            for i, r in enumerate(board, 1):
                index.append(f"| {i} | {r.author} | {r.overall_letter} | "
                             f"{r.overall_score:.1f} | {r.total_commits} |")
            index.append("")
            index.append(f"[Full review of {top.author}]({slug}/review.md)")
            index.append("")
            print(f"   top: {top.author} {top.overall_letter} {top.overall_score:.1f}")
        finally:
            shutil.rmtree(tmp_root, ignore_errors=True)
    index.append("*Generated by PIP. `pip install on-a-pip` and review your own history.*")
    index.append("")
    with open(os.path.join(ROOT, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(index))
    print("gallery written to", ROOT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
